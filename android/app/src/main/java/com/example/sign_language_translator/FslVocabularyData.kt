    INDEX_POINT,          // Index finger pointing
    TWO_INDEX_TOUCH,      // Two index fingers touching
    TWO_INDEX_STACKED,    // Two index fists stacked vertically
    TWO_INDEX_LOCKED,     // Two index fists locked after strike
    Y_HAND,               // Thumb and pinky extended ('Y' shape)
    Y_HAND_CHIN,          // 'Y' knuckles touching chin
