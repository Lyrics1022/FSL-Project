    PINCH_CLOSED,         // Beak snapped closed
    BENT_FLAT,            // 4 fingers flat & bent 90°
    A_HAND,               // Fist with thumb pointing straight up
    V_PEACE,              // 'V' peace sign near eye
    TWO_CUPPED,           // Both hands cupped with knuckles touching
    HORIZON_ARM_SUN_RISE, // Horizontal arm + hand rising like sun
    HORIZON_ARM_SUN_45,   // Horizontal arm + hand angled at 45°
    HORIZON_ARM_SUNSET,   // Horizontal arm + hand dipping downward
    THREE_HAND,           // Thumb + index + middle extended (3)
    FOUR_HAND,            // 4 fingers up, thumb folded (4)
    V_HAND,               // 'V' hand (2 fingers)
    C_HAND,               // Curved 'C' hand
    L_HAND,               // 'L' shape (thumb + index)
    F_HAND,               // Index + thumb circle, 3 fingers up (9 / F)
    W_HAND,               // Pinky touches thumb, 3 fingers up (6 / W)
    SEVEN_HAND,           // Ring finger touches thumb (7)
    EIGHT_HAND,           // Middle finger touches thumb (8)
    INDEX_CHIN,           // Index finger near chin / lips
    INDEX_FOREHEAD,       // Index finger at forehead / brow
    INDEX_CHEEK,          // Index finger near ear / cheek
    TWO_FLAT_HANDS,       // Both flat hands together
    TWO_FISTS             // Both closed fists together
}

